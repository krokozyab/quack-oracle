-- A table to write to. IDENTITY and DEFAULT are here on purpose: they are what
-- INSERT ... RETURNING and the "columns you do not name" rule demonstrate.
CREATE TABLE QUACK_DEMO_LOG (
    LOG_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    LABEL    VARCHAR2(50),
    AMOUNT   NUMBER(10,2),
    LOGGED_AT DATE DEFAULT SYSDATE
);

-- One row carrying one column of every type the type table in the README maps.
CREATE TABLE QUACK_DEMO_TYPES (
    N_INT       NUMBER(5,0),
    N_DECIMAL   NUMBER(10,5),
    N_ANY       NUMBER,
    V           VARCHAR2(20),
    C           CHAR(10),
    D           DATE,
    TS          TIMESTAMP(6),
    TS_NS       TIMESTAMP(9),
    TS_TZ       TIMESTAMP(6) WITH TIME ZONE,
    R           RAW(16),
    BF          BINARY_FLOAT,
    BD          BINARY_DOUBLE,
    N_NULL      NUMBER
);

