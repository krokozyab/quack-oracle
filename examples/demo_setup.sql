-- oracle_scanner demo schema.
--
-- Creates the objects the README's "Try it yourself" section and the examples
-- in duckdb_functions() use. Safe to run more than once: existing demo tables
-- are dropped first and the PL/SQL objects are replaced. Works on Oracle 19c,
-- 23ai Free and OCI Autonomous, in whatever schema you connect as.
--
--   sqlplus user/password@host:1521/service @demo_setup.sql

SET SERVEROUTPUT ON
WHENEVER SQLERROR CONTINUE

BEGIN
    FOR victim IN (SELECT table_name FROM user_tables
                   WHERE table_name IN ('QUACK_DEMO_DEPARTMENTS', 'QUACK_DEMO_LOG', 'QUACK_DEMO_TYPES'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || victim.table_name || ' PURGE';
    END LOOP;
END;
/

-- A small table to scan, filter and read in parallel. The key is NUMBER with
-- whole values, which is what oracle_scan_parallel requires.
CREATE TABLE QUACK_DEMO_DEPARTMENTS (
    DEPARTMENT_ID   NUMBER(6)    NOT NULL PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(40) NOT NULL,
    LOCATION        VARCHAR2(40),
    HEADCOUNT       NUMBER(6)
);

